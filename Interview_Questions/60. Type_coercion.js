    // Type coercion is automatic type conversion by JS engine during operation.

    '5' + 2             //  '52' (string concatenation)
    '5' - 2             //   3  (string -> number)
    true + 1            //   2  (true -> 1)
    false + 1           //   1  (false -> 0)


